import argparse
import random
from collections import defaultdict

def get_options():
    description = "Get's representatives from sketchlib distance calculations"
    parser = argparse.ArgumentParser(description=description,
                                        prog='python get_representatives.py')
    IO = parser.add_argument_group('Input/options.out')
    IO.add_argument('--infile',
                    required=True,
                    help='Pairwise interaction file generated by sketchlib-rust')
    IO.add_argument('--workflow',
                    default='reps',
                    choices=['reps', 'topN', 'reps_graph'],
                    help='Workflow to use. Either reps (representatives), topN (topN most distant genomes), or reps_graph (graph-based connected component representatives).')
    IO.add_argument('--min-return',
            default=1000,
            type=int,
            help='Minimum number of genomes to return. Default = 1000')
    IO.add_argument('--thresholds',
            default="0.98",
            type=str,
            help='Comma separated list of thresholds for deduplication. Default = 0.98')
    IO.add_argument('--query',
            default=False,
            action= "store_true",
            help='Specify if this is a queried sketchlib run.')
    IO.add_argument('--to-keep',
            default=None,
            type=str,
            help='File with list of sample IDs (one per line) to aim to retain as representatives. All other genomes will be ignored.')
    IO.add_argument('--verbose',
            default=False,
            action= "store_true",
            help='Enable verbose output.')
    IO.add_argument('--outpref',
                default="distances",
                help='Output prefix. Default = distances')
    return parser.parse_args()

def parse_thresholds(threshold_string):
    thresholds = threshold_string.split(",")
    return sorted([float(threshold) for threshold in thresholds], reverse=False)

# return topN most distance genomes
def topN(options):
    options = get_options()
    thresholds = parse_thresholds(options.thresholds)

    distance_counts = defaultdict(list)
    with open(options.infile, "r") as f1:
        for line in f1:
            split_line = line.rstrip().split("\t")

            # add distance to dictionary
            distance_counts[split_line[0]].append(float(split_line[2]))
    
    # Compute averages
    averages = {k: sum(v) / len(v) for k, v in distance_counts.items()}

    # Sort by average value
    sorted_items = sorted(averages.items(), key=lambda x: x[1])

    with open(options.outpref + "_reps.txt", "w") as f2, open(options.outpref + "_dists.txt", "w") as f3:
        for i in range(0, options.min_return):
            f2.write(str(sorted_items[i][0]) + "\n")
            f3.write(str(sorted_items[i][0]) + "\t" + str(sorted_items[i][1]) + "\n")

def return_reps(options):
    options = get_options()
    parsed_thresholds = parse_thresholds(options.thresholds)

    qc_reps_to_keep = set()
    if options.to_keep is not None:
        with open(options.to_keep, "r") as f:
            for line in f:
                qc_reps_to_keep.add(line.rstrip())

    threshold_dict = {}
    for threshold in parsed_thresholds:
        threshold_dict[threshold] = {"to_keep": set(), "to_ignore": set(), "max_distances": {}}

    # iterate through all thresholds, starting at lowest which then assigns genomes to higher thresholds
    with open(options.infile, "r") as f1:
        for line in f1:
            split_line = line.rstrip().split("\t")
            genome1, genome2, distance = split_line[0], split_line[1], float(split_line[2])

            # determine which genome should be being added
            # when querying, each genome will only be in second column
            # if not, each genome will always in the first column
            if options.query:
                query = genome1
                reference = genome2
            else:
                reference = genome1
                query = genome2

            # skip line if genome 1 not in qc representatives to keep
            if options.to_keep is not None and reference not in qc_reps_to_keep:
                continue

            # iterate through all thresholds, ensuring that genomes are added consistently across thresholds
            for threshold_idx, threshold in enumerate(parsed_thresholds):
                if reference in threshold_dict[threshold]["to_ignore"] or reference in threshold_dict[threshold]["to_keep"]:
                    # need to account for query if threshold met, need to ignore in future analysis
                    if distance >= threshold and query not in threshold_dict[threshold]["to_keep"]:
                        if options.verbose:
                            print(f"Adding {query} to ignore for threshold {threshold} because {reference} is already assigned and distance is above threshold.")
                        threshold_dict[threshold]["to_ignore"].add(query)
                    continue

                # if above distance, ignore second genome, take first as representative
                if distance >= threshold:
                    # add this representative to all higher thresholds, and add query to ignore for this threshold
                    for higher_threshold in parsed_thresholds[threshold_idx:]:
                        if options.verbose:
                            print(f"Adding {reference} to keep for threshold {higher_threshold}.")
                        # ensure query hasn't already been added as a representative for higher threshold, if so add to ignore instead
                        if query not in threshold_dict[higher_threshold]["to_keep"]:
                            threshold_dict[higher_threshold]["to_keep"].add(reference)
                        else:
                            # otherwise add reference to ignore for this threshold, and add to ignore for all higher thresholds
                            if options.verbose:
                                print(f"Adding {reference} to ignore for threshold {higher_threshold} because it is already a representative.")
                            threshold_dict[higher_threshold]["to_ignore"].add(reference)
                    if options.verbose:
                        print(f"Adding {query} to ignore for threshold {threshold}.")
                    threshold_dict[threshold]["to_ignore"].add(query)
                else:
                    # keep track of max distance in case no distances are above threshold, need to add later
                    if reference in threshold_dict[threshold]["max_distances"]:
                        if distance > threshold_dict[threshold]["max_distances"][reference]:
                            if options.verbose:
                                print(f"Updating max distance for {reference} to {distance} for threshold {threshold}.")
                            threshold_dict[threshold]["max_distances"][reference] = distance
                    else:
                        if options.verbose:
                            print(f"Adding max distance for {reference} to {distance} for threshold {threshold}.")
                        threshold_dict[threshold]["max_distances"][reference] = distance
            
            # line_count += 1
            # if line_count % 1000000 == 0:
            #     print(f"Distance count: {line_count}")
    
    # go through max_distances to see if any other genomes must be added
    counter = 0
    for threshold in parsed_thresholds:
        if options.verbose:
            print(f"Processing threshold {threshold}.")
            print(f"{threshold_dict[threshold]['to_keep']} genomes kept and {threshold_dict[threshold]['to_ignore']} genomes ignored for threshold {threshold} before checking max distances.")

        for key, value in threshold_dict[threshold]["max_distances"].items():
            if key not in threshold_dict[threshold]["to_keep"] and key not in threshold_dict[threshold]["to_ignore"]:
                if value < threshold:
                    threshold_dict[threshold]["to_keep"].add(key)
                    counter += 1
        
        if options.verbose:
            print(f"{threshold_dict[threshold]['to_keep']} genomes kept and {threshold_dict[threshold]['to_ignore']} genomes ignored for threshold {threshold} after checking max distances.")
        
        print(f"Adding {counter} genomes with all distances below threshold {threshold}.")
    
        # determine length of to_keep and add random to_ignore to make up remaining missing genomes
        num_keep = len(threshold_dict[threshold]["to_keep"])
        remaining = options.min_return - num_keep
        if remaining > 0:
            num_ignore = len(threshold_dict[threshold]["to_ignore"])

            if remaining > num_ignore:
                remaining = num_ignore
            
            print(f"Adding {remaining} genomes to make up numbers.")

            added = 0
            for element in threshold_dict[threshold]["to_ignore"]:
                threshold_dict[threshold]["to_keep"].add(element)
                added += 1

                if added >= remaining:
                    break

        with open(options.outpref + f"_{threshold}_reps.txt", "w") as f2:
            for genome in threshold_dict[threshold]["to_keep"]:
                f2.write(str(genome) + "\n")

def return_reps_graph(options):
    """Graph-based alternative to return_reps.

    Builds an undirected graph where an edge between two genomes means their
    distance is >= threshold (i.e. they are similar enough to be deduplicated).
    Connected components are found with union-find, and one random representative
    is selected per component.  This correctly handles transitivity: if A~B and
    B~C then A, B and C all belong to the same component and produce a single
    representative, regardless of the order pairs appear in the input file.
    """
    parsed_thresholds = parse_thresholds(options.thresholds)

    qc_reps_to_keep = set()
    if options.to_keep is not None:
        with open(options.to_keep, "r") as f:
            for line in f:
                qc_reps_to_keep.add(line.rstrip())

    # Single pass: collect all genomes and per-threshold edges
    all_genomes = set()
    edges_per_threshold = {threshold: [] for threshold in parsed_thresholds}

    with open(options.infile, "r") as f1:
        for line in f1:
            split_line = line.rstrip().split("\t")
            genome1, genome2, distance = split_line[0], split_line[1], float(split_line[2])

            if options.query:
                query, reference = genome1, genome2
            else:
                reference, query = genome1, genome2

            if options.to_keep is not None and reference not in qc_reps_to_keep:
                continue

            all_genomes.add(reference)
            all_genomes.add(query)

            for threshold in parsed_thresholds:
                if distance >= threshold:
                    edges_per_threshold[threshold].append((reference, query))

    # Union-Find with path compression and union by rank
    def make_uf(nodes):
        parent = {n: n for n in nodes}
        rank = {n: 0 for n in nodes}

        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]  # path halving
                x = parent[x]
            return x

        def union(x, y):
            px, py = find(x), find(y)
            if px == py:
                return
            if rank[px] < rank[py]:
                px, py = py, px
            parent[py] = px
            if rank[px] == rank[py]:
                rank[px] += 1

        return find, union

    # Track organic representatives across thresholds to enforce nesting.
    # As threshold increases, components can only split (never merge), so each
    # sub-component at a higher threshold contains at most one inherited rep.
    previous_organic = set()

    for threshold in parsed_thresholds:
        find, union = make_uf(all_genomes)

        for ref, qry in edges_per_threshold[threshold]:
            union(ref, qry)

        # Group genomes by component root
        components = defaultdict(list)
        for genome in all_genomes:
            components[find(genome)].append(genome)

        if options.verbose:
            print(f"Threshold {threshold}: {len(components)} connected components from {len(all_genomes)} genomes.")

        # Pick one representative per component.
        # If the component already contains a rep chosen at a lower threshold,
        # inherit it so that representative sets are nested across thresholds.
        # Otherwise prefer QC-listed genomes, then fall back to random.
        organic_representatives = set()
        for component_genomes in components.values():
            inherited = [g for g in component_genomes if g in previous_organic]
            if inherited:
                organic_representatives.update(inherited)
            else:
                if qc_reps_to_keep:
                    preferred = [g for g in component_genomes if g in qc_reps_to_keep]
                    rep = random.choice(preferred) if preferred else random.choice(component_genomes)
                else:
                    rep = random.choice(component_genomes)
                organic_representatives.add(rep)

        # Top up to min_return if needed (top-up genomes are not carried forward)
        representatives = set(organic_representatives)
        remaining = options.min_return - len(representatives)
        if remaining > 0:
            non_reps = [g for g in all_genomes if g not in representatives]
            additional = random.sample(non_reps, min(remaining, len(non_reps)))
            representatives.update(additional)
            print(f"Adding {len(additional)} genomes to meet min_return for threshold {threshold}.")

        print(f"Threshold {threshold}: {len(representatives)} representatives from {len(components)} components.")

        with open(options.outpref + f"_{threshold}_reps.txt", "w") as f2:
            for genome in representatives:
                f2.write(str(genome) + "\n")

        previous_organic = organic_representatives


def main():
    options = get_options()

    if options.workflow == "reps":
        return_reps(options)
    elif options.workflow == "reps_graph":
        return_reps_graph(options)
    else:
        topN(options)

if __name__ == "__main__":
    main()
