import argparse
from collections import defaultdict

def get_options():
    description = "Get's representatives from sketchlib distance calculations"
    parser = argparse.ArgumentParser(description=description,
                                        prog='python get_representatives.py')
    IO = parser.add_argument_group('Input/options.out')
    IO.add_argument('--infile',
                    required=True,
                    help='Pairwise interaction file generated by sketchlib-rust')
    IO.add_argument('--workflow',
                    default='reps',
                    choices=['reps', 'topN'],
                    help='Workflow to use. Either reps (representatives) or topN (topN most distant genomes).')
    IO.add_argument('--min-return',
            default=1000,
            type=int,
            help='Minimum number of genomes to return. Default = 1000')
    IO.add_argument('--threshold',
            default=0.98,
            type=float,
            help='Threshold for deduplication. Default = 0.98')
    IO.add_argument('--query',
            default=False,
            action= "store_true",
            help='Specify if this is a queried sketchlib run.')
    IO.add_argument('--outpref',
                default="distances",
                help='Output prefix. Default = distances')
    return parser.parse_args()

# return topN most distance genomes
def topN(options):
    options = get_options()

    distance_counts = defaultdict(list)
    with open(options.infile, "r") as f1:
        for line in f1:
            split_line = line.rstrip().split("\t")

            # add distance to dictionary
            distance_counts[split_line[0]].append(float(split_line[2]))
    
    # Compute averages
    averages = {k: sum(v) / len(v) for k, v in distance_counts.items()}

    # Sort by average value
    sorted_items = sorted(averages.items(), key=lambda x: x[1])

    with open(options.outpref + "_reps.txt", "w") as f2, open(options.outpref + "_dists.txt", "w") as f3:
        for i in range(0, options.min_return):
            f2.write(str(sorted_items[i][0]) + "\n")
            f3.write(str(sorted_items[i][0]) + "\t" + str(sorted_items[i][1]) + "\n")

def return_reps(options):
    options = get_options()

    to_ignore = set()
    to_keep = set()
    max_distances = {}
    line_count = 0
    with open(options.infile, "r") as f1:
        for line in f1:
            split_line = line.rstrip().split("\t")
            genome1, genome2, distance = split_line[0], split_line[1], float(split_line[2])

            # determine which genome should be being added
            # when querying, each genome will only be in second column
            # if not, each genome will always in the first column
            if options.query:
                query = genome1
                reference = genome2
            else:
                reference = genome1
                query = genome2

            # if reference seen before, ignore
            if reference in to_ignore or reference in to_keep:
                # need to account for query if threshold met, need to ignore in future analysis
                if distance >= options.threshold:
                    to_ignore.add(query)
                continue

            # if above distance, ignore second genome, take first as representative
            if distance >= options.threshold:
                to_keep.add(reference)
                to_ignore.add(query)
            else:
                # keep track of max distance in case no distances are above threshold, need to add later
                if reference in max_distances:
                    if distance > max_distances[reference]:
                        max_distances[reference] = distance
                else:
                    max_distances[reference] = distance
            
            # line_count += 1
            # if line_count % 1000000 == 0:
            #     print(f"Distance count: {line_count}")
    
    # go through max_distances to see if any other genomes must be added
    counter = 0
    for key, value in max_distances.items():
        if key not in to_keep and key not in to_ignore:
            if value < options.threshold:
                to_keep.add(key)
                counter += 1
    
    print(f"Adding {counter} genomes with all distances below threshold.")
    
    # determine length of to_keep and add random to_ignore to make up remaining missing genomes
    num_keep = len(to_keep)
    remaining = options.min_return - num_keep
    if remaining > 0:
        num_ignore = len(to_ignore)

        if remaining > num_ignore:
            remaining = num_ignore
        
        print(f"Adding {remaining} genomes to make up numbers.")

        added = 0
        for element in to_ignore:
            to_keep.add(element)
            added += 1

            if added >= remaining:
                break

    with open(options.outpref + "_reps.txt", "w") as f2:
        for genome in to_keep:
            f2.write(str(genome) + "\n")

def main():
    options = get_options()

    if options.workflow == "reps":
        return_reps(options)
    else:
        topN(options)

if __name__ == "__main__":
    main()
